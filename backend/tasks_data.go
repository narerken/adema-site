const itemsPerDay = 5

// taskListForDay возвращает itemsPerDay 
func taskListForDay(day int) []string {
	n := len(dailyTasks)
	if n == 0 {
		return nil
	}
	start := (day * itemsPerDay) % n
	count := itemsPerDay
	if count > n {
		count = n
	}
	out := make([]string, 0, count)
	for i := 0; i < count; i++ {
		out = append(out, dailyTasks[(start+i)%n])
	}
	return out
}
